#!/usr/bin/env python3
"""生成 crates/guanxiang-core/src/delta_t_table.rs。

数据来源（USNO，基于 IERS 观测）：
  historic_deltat.data  https://maia.usno.navy.mil/ser7/historic_deltat.data  （1657–1984，半年一值）
  deltat.data           https://maia.usno.navy.mil/ser7/deltat.data           （1973-02 起，逐月）

用法：
  python tools/deltat/gen_table.py historic_deltat.data deltat.data crates/guanxiang-core/src/delta_t_table.rs

只用标准库。1800.0–1972.5 取半年值，1973-02 起取逐月值。
"""

import sys
from datetime import date

START_YEAR = 1800.0
MONTHLY_FROM = 1973.0  # 此后改用逐月值


def mjd(y: int, m: int, d: int) -> float:
    return float((date(y, m, d) - date(1858, 11, 17)).days)


def decimal_year_to_mjd(t: float) -> float:
    y = int(t)
    frac = t - y
    start = mjd(y, 1, 1)
    days = mjd(y + 1, 1, 1) - start
    return start + frac * days


def main() -> None:
    hist_path, monthly_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    rows = []

    with open(hist_path, encoding="ascii") as f:
        for line in f:
            parts = line.split()
            if len(parts) < 2:
                continue
            try:
                t, dt = float(parts[0]), float(parts[1])
            except ValueError:
                continue
            if START_YEAR <= t < MONTHLY_FROM:
                rows.append((decimal_year_to_mjd(t), dt))

    with open(monthly_path, encoding="ascii") as f:
        for line in f:
            parts = line.split()
            if len(parts) != 4:
                continue
            y, m, d = int(parts[0]), int(parts[1]), int(parts[2])
            rows.append((mjd(y, m, d), float(parts[3])))

    rows.sort()
    for (a, _), (b, _) in zip(rows, rows[1:]):
        assert b > a, f"MJD 不递增：{a} {b}"

    last = rows[-1][0]
    ly = date(1858, 11, 17).toordinal() + int(last)
    last_date = date.fromordinal(ly)

    out = open(out_path, "w", encoding="utf-8", newline="\n")
    out.write("// @generated by tools/deltat/gen_table.py — 不要手改。\n")
    out.write("//\n")
    out.write("// ΔT = TT − UT1（秒），自变量为 MJD（UT）。\n")
    out.write("// 1800.0–1972.5：USNO historic_deltat.data（半年一值）；\n")
    out.write("// 1973-02 起：USNO deltat.data（逐月，由 IERS 观测得出）。\n")
    out.write(f"// 最后一个值：{last_date.isoformat()}。\n\n")
    out.write(f"pub(crate) const TABLE: [(f64, f64); {len(rows)}] = [\n")
    for m, dt in rows:
        out.write(f"    ({m:.1f}, {dt}),\n")
    out.write("];\n")
    out.close()


if __name__ == "__main__":
    main()
