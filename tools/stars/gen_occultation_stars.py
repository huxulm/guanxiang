#!/usr/bin/env python3
"""从 Hipparcos 主星表生成月掩星用的精简星表 crates/guanxiang-core/src/stars_table.rs。

数据：NASA HEASARC 的 Hipparcos 主星表（与 CDS I/239 相同内容）
  https://heasarc.gsfc.nasa.gov/FTP/heasarc/dbase/tdat_files/heasarc_hipparcos.tdat.gz

选取：V < 6.0，且 J2000 黄纬 |β| < 6.6°（月球黄纬最大约 5.3°，加上视差约 1° 和月球半径 0.27°）。
坐标为 ICRS、历元 J1991.25；自行 pmRA 已含 cos δ（μα*）。

用法：
  python tools/stars/gen_occultation_stars.py heasarc_hipparcos.tdat.gz crates/guanxiang-core/src/stars_table.rs
"""

import gzip
import math
import sys

V_LIMIT = 6.0
BETA_LIMIT_DEG = 6.6
EPS_J2000 = math.radians(84381.406 / 3600.0)

# 常见亮星的中文名
NAMES = {
    21421: "毕宿五",  # Aldebaran
    49669: "轩辕十四",  # Regulus
    65474: "角宿一",  # Spica
    80763: "心宿二",  # Antares
    17702: "昴宿六",  # Alcyone
    17499: "昴宿一",  # Electra
    17531: "昴宿二",  # Taygeta
    17573: "昴宿四",  # Maia
    17608: "昴宿五",  # Merope
    17847: "昴宿七",  # Atlas
    20889: "毕宿四",  # Ain (ε Tau)
    20894: "毕宿六",  # θ² Tau
    25428: "五车五",  # Elnath (β Tau)
    42911: "鬼宿四",  # Asellus Australis (δ Cnc)
    61941: "东上相",  # Porrima (γ Vir)
    78401: "房宿三",  # Dschubba (δ Sco)
    78820: "房宿四",  # Acrab (β¹ Sco)
    92855: "斗宿四",  # Nunki (σ Sgr)
    76333: "氐宿一",  # Zubenelgenubi (α² Lib)
}


def ecliptic_latitude(ra_deg, dec_deg):
    ra, dec = math.radians(ra_deg), math.radians(dec_deg)
    x, y, z = math.cos(dec) * math.cos(ra), math.cos(dec) * math.sin(ra), math.sin(dec)
    ze = -math.sin(EPS_J2000) * y + math.cos(EPS_J2000) * z
    return math.degrees(math.asin(ze))


def main() -> None:
    src, out_path = sys.argv[1], sys.argv[2]
    rows = []
    with gzip.open(src, "rt", encoding="latin-1") as f:
        in_data = False
        for line in f:
            if line.startswith("<DATA>"):
                in_data = True
                continue
            if not in_data or line.startswith("<END>"):
                continue
            c = line.rstrip("\n").split("|")
            if len(c) < 16 or not c[7] or not c[10] or not c[14]:
                continue
            hip, vmag = int(c[5]), float(c[7])
            if vmag >= V_LIMIT:
                continue
            ra, dec = float(c[10]), float(c[11])
            if abs(ecliptic_latitude(ra, dec)) >= BETA_LIMIT_DEG:
                continue
            plx = float(c[13]) if c[13] else 0.0
            pmra, pmdec = float(c[14]), float(c[15])
            rows.append((ra, hip, vmag, dec, plx, pmra, pmdec))
    rows.sort()

    with open(out_path, "w", encoding="utf-8", newline="\n") as out:
        out.write("// @generated by tools/stars/gen_occultation_stars.py — 不要手改。\n")
        out.write("//\n")
        out.write("// Hipparcos 主星表（ESA 1997，经 NASA HEASARC），V < 6.0、J2000 黄纬 |β| < 6.6°。\n")
        out.write("// 坐标 ICRS、历元 J1991.25（度）；视差 mas；自行 mas/年，pm_ra 含 cos δ。按赤经排序。\n\n")
        out.write("use crate::stars::Star;\n\n")
        out.write(f"pub(crate) static STARS: [Star; {len(rows)}] = [\n")
        for ra, hip, vmag, dec, plx, pmra, pmdec in rows:
            name = f'Some("{NAMES[hip]}")' if hip in NAMES else "None"
            out.write(
                f"    Star {{ hip: {hip}, name: {name}, vmag: {vmag:.2f}, ra_deg: {ra:.8f}, dec_deg: {dec:.8f}, "
                f"parallax_mas: {plx:.2f}, pm_ra_mas: {pmra:.2f}, pm_dec_mas: {pmdec:.2f} }},\n"
            )
        out.write("];\n")
    missing = [h for h in NAMES if h not in {r[1] for r in rows}]
    print(f"{len(rows)} 颗；有中文名但不在表中：{missing}", file=sys.stderr)


if __name__ == "__main__":
    main()
